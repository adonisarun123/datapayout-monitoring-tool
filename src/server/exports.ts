import type { getBill } from "./bills";
import type { Report } from "./reports";
import { getSettings } from "./settings";

type BillDetail = Awaited<ReturnType<typeof getBill>>;

function fmt(v: unknown): unknown {
  if (v instanceof Date) return formatInstantIST(v);
  return v ?? "";
}

/** Section 14: every export carries its filters, generation time, date basis and the user who ran it. */
export async function reportCsv(report: Report, actor: Actor): Promise<string> {
  const settings = await getSettings();
  const preamble: [string, unknown][] = [
    ["Organization", settings.organization_name],
    ["Report", report.title],
    ["Generated at", formatInstantIST(new Date())],
    ["Generated by", `${actor.name} <${actor.email}>`],
    ["Filters", Object.entries(report.filters).map(([k, v]) => `${k}=${v}`).join("; ") || "none"],
    ["Date basis", report.basis],
    ["Currency", "Amounts are in the currency shown on each row; currencies are never combined."],
  ];
  const rows = report.rows.map((r) => report.columns.map((c) => fmt(r[c.key])));
  for (const t of report.totals ?? [])
    rows.push(report.columns.map((c, i) => (i === 0 ? `TOTAL ${t.currency ?? ""}`.trim() : c.key === "currency" ? t.currency : c.numeric ? fmt(t[c.key === "line_amount" ? "amount" : c.key]) : "")));
  return toCsv(report.columns.map((c) => c.label), rows, preamble);
}

export function billLabel(bill: BillDetail["bill"]): string {
  return bill.status === "APPROVED" ? "APPROVED" : `NOT APPROVED (${bill.status.replace(/_/g, " ")})`;
}

export async function billCsv(detail: BillDetail, actor: Actor): Promise<string> {
  const { bill, lines } = detail;
  const settings = await getSettings();
  const adj = bill.type === "ADJUSTMENT";
  const preamble: [string, unknown][] = [
    ["Organization", settings.organization_name],
    ["Document", adj ? "Adjustment statement (not a tax invoice)" : "Payout statement (not a tax invoice)"],
    ["Statement number", bill.bill_number],
    ["Status", billLabel(bill)],
    ...(adj ? ([["Adjusts", bill.original_bill_number], ["Reason", bill.adjustment_reason]] as [string, unknown][]) : []),
    ["POC", bill.poc_name],
    ["Period", `${bill.date_from} to ${bill.date_to_inclusive} (activity dates, Asia/Kolkata)`],
    ["Currency", bill.currency],
    ["Total", bill.total],
    ["Paid", bill.paid],
    ["Outstanding", bill.outstanding],
    ["Approved by", bill.approved_by_name ?? ""],
    ["Approved at", formatInstantIST(bill.approved_at)],
    ["Generated at", formatInstantIST(new Date())],
    ["Generated by", `${actor.name} <${actor.email}>`],
    ["Note", "Payout before any taxes or other adjustments. Line amounts are rounded half up to 2 decimals, then summed."],
  ];
  const headers = ["Activity date", "Device", "Reference", "Hours", "Payout %", "Rate", "Payable hours", "Currency",
    ...(adj ? ["Original amount", "Prior adjustments", "Corrected amount"] : []), adj ? "Adjustment" : "Amount"];
  const rows = lines.map((l) => [l.activity_date, l.device_code, l.reference, l.hours, l.percentage, l.rate,
    dec(l.payable_hours_raw).toDecimalPlaces(4).toFixed(4), l.currency,
    ...(adj ? [l.original_amount, l.prior_adjustments, l.corrected_amount] : []), l.line_amount]);
  rows.push(["TOTAL", "", "", "", "", "", "", bill.currency, ...(adj ? ["", "", ""] : []), bill.total]);
  return toCsv(headers, rows, preamble);
}

// Standard PDF fonts only cover Latin-1; anything else is replaced so generation never fails.
const latin = (s: unknown) => String(s ?? "").replace(/[^\x20-\x7E\xA0-\xFF]/g, "?");

/** FR-025: server-side PDF of a bill, clearly labelled approved or not, never presented as a tax invoice. */
export async function billPdf(detail: BillDetail, actor: Actor): Promise<Uint8Array> {
  const { bill, lines, payments } = detail;
  const settings = await getSettings();
  const adj = bill.type === "ADJUSTMENT";
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const W = 595.28, H = 841.89, M = 40;
  let page: PDFPage = pdf.addPage([W, H]);
  let y = H - M;
  const text = (s: unknown, x: number, size = 9, f: PDFFont = font, color = rgb(0.1, 0.1, 0.12)) =>
    page.drawText(latin(s), { x, y, size, font: f, color });
  const right = (s: unknown, xRight: number, size = 9, f: PDFFont = font) => {
    const str = latin(s);
    page.drawText(str, { x: xRight - f.widthOfTextAtSize(str, size), y, size, font: f, color: rgb(0.1, 0.1, 0.12) });
  };
  const cols = adj
    ? [{ h: "Date", x: M }, { h: "Device", x: 100 }, { h: "Reference", x: 175 }, { h: "Original", r: 370 }, { h: "Prior adj.", r: 430 }, { h: "Corrected", r: 495 }, { h: "Adjustment", r: W - M }]
    : [{ h: "Date", x: M }, { h: "Device", x: 100 }, { h: "Reference", x: 175 }, { h: "Hours", r: 345 }, { h: "%", r: 385 }, { h: "Rate", r: 440 }, { h: "Payable h", r: 500 }, { h: "Amount", r: W - M }];
  const header = () => {
    for (const c of cols) "x" in c && c.x !== undefined ? text(c.h, c.x, 8, bold) : right(c.h, (c as any).r, 8, bold);
    y -= 4;
    page.drawLine({ start: { x: M, y }, end: { x: W - M, y }, thickness: 0.5, color: rgb(0.6, 0.6, 0.6) });
    y -= 12;
  };

  text(settings.organization_name, M, 14, bold); y -= 18;
  text(adj ? "Adjustment statement" : "Payout statement", M, 11, bold);
  right(billLabel(bill), W - M, 11, bold); y -= 13;
  text("This statement is not a tax invoice. Amounts are payouts before any taxes or other adjustments.", M, 8, font, rgb(0.4, 0.4, 0.4)); y -= 20;
  const meta: [string, unknown][] = [
    ["Statement number", bill.bill_number],
    ...(adj ? ([["Adjusts bill", bill.original_bill_number], ["Reason", bill.adjustment_reason]] as [string, unknown][]) : []),
    ["POC", bill.poc_name],
    ["Period (activity dates, IST)", `${bill.date_from} to ${bill.date_to_inclusive}`],
    ["Currency", bill.currency],
    ["Prepared by", bill.created_by_name],
    ["Approved by", bill.approved_by_name ? `${bill.approved_by_name}, ${formatInstantIST(bill.approved_at)}` : "Not approved"],
  ];
  for (const [k, v] of meta) { text(k, M, 9, bold); text(String(v ?? "").slice(0, 90), M + 150); y -= 13; }
  y -= 8;
  header();
  for (const l of lines) {
    if (y < M + 90) { page = pdf.addPage([W, H]); y = H - M; header(); }
    text(l.activity_date, M, 8); text(String(l.device_code).slice(0, 14), 100, 8); text(String(l.reference).slice(0, adj ? 24 : 22), 175, 8);
    if (adj) { right(l.original_amount, 370, 8); right(l.prior_adjustments, 430, 8); right(l.corrected_amount, 495, 8); }
    else { right(l.hours, 345, 8); right(dec(l.percentage).toFixed(2), 385, 8); right(l.rate, 440, 8); right(dec(l.payable_hours_raw).toDecimalPlaces(4).toFixed(4), 500, 8); }
    right(l.line_amount, W - M, 8);
    y -= 12;
  }
  y -= 2;
  page.drawLine({ start: { x: M, y }, end: { x: W - M, y }, thickness: 0.5, color: rgb(0.6, 0.6, 0.6) });
  y -= 14;
  const summary: [string, string][] = [["Total", `${bill.currency} ${bill.total}`]];
  if (bill.status === "APPROVED" && bill.payment_status !== "CREDIT")
    summary.push(["Paid", `${bill.currency} ${bill.paid}`], ["Outstanding", `${bill.currency} ${bill.outstanding}`]);
  if (bill.payment_status === "CREDIT") summary.push(["Treatment", "Credit, reconciled outside this tool"]);
  for (const [k, v] of summary) { right(k, 440, 10, bold); right(v, W - M, 10, bold); y -= 14; }
  if (payments.length) {
    y -= 6; text("Payment ledger", M, 9, bold); y -= 12;
    for (const p of payments) {
      if (y < M + 40) { page = pdf.addPage([W, H]); y = H - M; }
      text(`${p.payment_date}  ${p.kind}  ${p.method}  ref ${p.reference}`.slice(0, 95), M, 8);
      right(`${p.kind === "REVERSAL" ? "-" : ""}${p.amount}`, W - M, 8); y -= 11;
    }
  }
  const pages = pdf.getPages();
  pages.forEach((p, i) => {
    p.drawText(latin(`Generated ${formatInstantIST(new Date())} by ${actor.name}. Line amounts rounded half up to 2 decimals, then summed. Page ${i + 1} of ${pages.length}`), {
      x: M, y: 24, size: 7, font, color: rgb(0.45, 0.45, 0.45),
    });
  });
  return pdf.save();
}
